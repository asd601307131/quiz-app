/** 按 id 建索引 */
export const QUESTION_MAP = new Map(QUESTIONS.map((q) => [q.id, q]));

export function getQuestion(id) {
  return QUESTION_MAP.get(id) || null;
}

export function getChapter(chapterId) {
  return CHAPTERS.find((c) => c.id === chapterId) || null;
}

/** 章节统计：题目数、各难度数量 */
export function chapterStats(chapterId) {
  const list = QUESTIONS.filter((q) => q.chapterId === chapterId);
  const by = { easy: 0, medium: 0, hard: 0 };
  list.forEach((q) => {
    by[q.difficulty] = (by[q.difficulty] || 0) + 1;
  });
  return { total: list.length, ...by };
}

