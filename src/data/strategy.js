export function getStrategySubject(subjectId) {
  return STRATEGY_SUBJECTS.find((s) => s.id === subjectId) || null;
}

export function getStrategyTopic(topicId) {
  return STRATEGY_TOPICS.find((t) => t.id === topicId) || null;
}

export function topicsOfSubject(subjectId) {
  return STRATEGY_TOPICS.filter((t) => t.subject === subjectId);
}

